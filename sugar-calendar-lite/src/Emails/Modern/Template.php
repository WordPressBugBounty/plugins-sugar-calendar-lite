<?php

namespace Sugar_Calendar\Emails\Modern;

use Sugar_Calendar\Emails\Styling;

/**
 * The Modern email shell.
 *
 * Layout-agnostic chrome: the document, the single media query, the accent band
 * and header image, the message card, the body-card wrapper, and the powered-by
 * row. It knows nothing about tickets, orders, or RSVPs, allowing the order
 * receipt and RSVP "Going" email to reuse it.
 *
 * Client rules this markup obeys: tables only, every base style inline (Gmail
 * strips head styles), a fluid container so an ignored media query shrinks
 * rather than overflows, no web fonts, no background images, no positioning.
 *
 * @since 3.14.0
 */
class Template {

	/**
	 * The marker `add_online_meeting_email_filter()` searches for.
	 *
	 * That filter injects the online-meeting Join Link before this marker. Its
	 * fallback branch treats a message WITHOUT the marker as plain text and
	 * appends a plain-text block, which on an HTML document lands after
	 * `</html>`. Do not change the string, and do not emit it bare: layouts emit
	 * it through `injection_row()`, which is where the reasoning lives.
	 *
	 * @since 3.14.0
	 *
	 * @var string
	 */
	const CONTENT_END_MARKER = '<!-- End Content -->';

	/**
	 * The font stack for every Modern email.
	 *
	 * Issue #517 specifies an Arial-based sans-serif stack. Figma uses Inter and
	 * Instrument Sans; neither is a web-safe email font.
	 *
	 * @since 3.14.0
	 *
	 * @var string
	 */
	const FONT_STACK = 'Arial, Helvetica, sans-serif';

	/**
	 * Divider between body-card sections.
	 *
	 * Shell chrome rather than layout content: every Modern layout separates its
	 * sections with this hairline, so it lives here instead of forcing the next
	 * layout to import a sibling layout for a border string.
	 *
	 * @since 3.14.0
	 *
	 * @var string
	 */
	const DIVIDER = 'border-top:2px dashed rgba(141, 141, 141, 0.15);';

	/**
	 * Where the accent band ends behind the message card, as a percentage of the
	 * card's wrapper cell (the card plus the 24px gap below it).
	 *
	 * A percentage rather than Figma's fixed 200px band: the message is
	 * user-editable, so the card height varies, and with no header image a fixed
	 * band would swallow the card entirely.
	 *
	 * @since 3.14.0
	 *
	 * @var int
	 */
	const MESSAGE_CARD_BAND_STOP = 60;

	/**
	 * Fixed accent depth behind an overlapping body card.
	 *
	 * Unlike the user-editable message card, the body card's top chrome is
	 * stable, so a fixed depth gives it a consistent accent transition.
	 *
	 * @since 3.14.0
	 *
	 * @var int
	 */
	private const BODY_CARD_OVERLAP_DEPTH = 48;

	/**
	 * The row that carries the injection marker.
	 *
	 * **Every Modern layout must emit this exactly once**, between its content
	 * and its footer. Two reasons, both silent when ignored:
	 *
	 * 1. `add_online_meeting_email_filter()` branches on
	 *    `strpos( $message, '<!-- End Content -->' )`. A layout without the marker
	 *    takes the else branch, which appends the online-meeting Join Link as
	 *    **plain text after `</html>`** on every email for an event with a
	 *    meeting. No error, visible only in a delivered inbox.
	 * 2. The marker has to sit inside a `<td>`, not loose between `</tr>` and
	 *    `<tr>`. HTML5's "in table" insertion mode foster-parents an injected
	 *    `<div>` or `<p>` out of the table entirely, so the Join Link renders
	 *    above the whole body card, on the page background, outside the card's
	 *    border. Emitting the bare constant reintroduces that.
	 *
	 * Vertical padding is 0 so the cell adds no height when nothing is injected,
	 * and the typography is real (not `font-size:0`) because injected markup
	 * carries no font size of its own and would inherit an invisible one.
	 *
	 * @since 3.14.0
	 *
	 * @return string
	 */
	public static function injection_row() {

		return '<tr><td style="padding:0 24px;font-family:' . self::FONT_STACK
			. ';font-size:14px;line-height:1.4;color:#333333;">'
			. self::CONTENT_END_MARKER
			. '</td></tr>';
	}

	/**
	 * Render a complete Modern email document.
	 *
	 * @since 3.14.0
	 *
	 * @param string $message_html The user's Email Message, already escaped and
	 *                             paragraph-wrapped by the caller. Empty hides
	 *                             the card entirely.
	 * @param string $body_html    The layout's body-card rows. Already escaped
	 *                             markup generated by us; not re-filtered here.
	 *                             Complete `<tr>` rows, since they are dropped
	 *                             straight into the body-card `<table>`.
	 * @param array  $styling      Values from `Styling::get()`. A partial array
	 *                             is safe: this is a cross-plugin entry point,
	 *                             and missing keys fall back to the defaults.
	 *
	 * @return string
	 */
	public static function render( string $message_html, string $body_html, array $styling ): string {

		$styling = self::normalize_styling( $styling );
		$colors  = $styling['colors'];

		return sprintf(
			"<!DOCTYPE html>\n<html %s>\n%s\n%s\n</html>\n",
			get_language_attributes( 'html' ),
			self::head(),
			self::body( $message_html, $body_html, $styling, $colors )
		);
	}

	/**
	 * Fill in any styling key the caller left out.
	 *
	 * Mirrors the merge `Styling::get()` performs, including the nested colors,
	 * so a consumer in another plugin can hand over the two or three values it
	 * cares about without every read site needing its own fallback.
	 *
	 * @since 3.14.0
	 *
	 * @param array $styling Styling values, possibly partial.
	 *
	 * @return array
	 */
	private static function normalize_styling( array $styling ): array {

		$defaults = Styling::defaults();

		$styling           = array_merge( $defaults, $styling );
		$styling['colors'] = array_merge( $defaults['colors'], (array) $styling['colors'] );

		return $styling;
	}

	/**
	 * The document head.
	 *
	 * The style block carries one media query, which stacks the button pair and
	 * the order grid on narrow screens, and nothing else.
	 * Gmail's web client strips it, and the fluid container means that degrades
	 * to the desktop layout instead of breaking.
	 *
	 * @since 3.14.0
	 *
	 * @return string
	 */
	private static function head() {

		return '<head>'
			. '<meta http-equiv="Content-Type" content="text/html; charset=UTF-8" />'
			. '<meta name="viewport" content="width=device-width, initial-scale=1" />'
			. '<title>' . esc_html( get_bloginfo( 'name' ) ) . '</title>'
			. '<style type="text/css">'
			. '@media only screen and (max-width:600px){'
			. '.sc-email-btn-cell{display:block !important;width:100% !important;padding:0 0 12px 0 !important;}'
			. '.sc-email-btn-cell-last{padding-bottom:0 !important;}'
			. '.sc-email-grid-cell{display:block !important;width:100% !important;padding:0 0 24px 0 !important;}'
			. '}'
			. '</style>'
			. '</head>';
	}

	/**
	 * The document body: accent region, then background region.
	 *
	 * @since 3.14.0
	 *
	 * @param string $message_html Message card contents, or empty.
	 * @param string $body_html    Body-card rows.
	 * @param array  $styling      Styling values.
	 * @param array  $colors       Color values.
	 *
	 * @return string
	 */
	private static function body( $message_html, $body_html, $styling, $colors ) {

		$body_card         = self::body_card( $body_html, $colors );
		$overlap_body_card = trim( $message_html ) === '';

		return sprintf(
			'<body style="margin:0;padding:0;background-color:%1$s;">'
			. '<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" border="0"'
			. ' style="background-color:%1$s;">'
			. '<tr><td align="center" style="padding:0;">%2$s</td></tr>'
			. '<tr><td align="center" style="padding:0 24px 42px 24px;">%3$s</td></tr>'
			. '</table>'
			. '</body>',
			esc_attr( $colors['background'] ),
			self::accent_region( $message_html, $body_card, $styling, $colors, $overlap_body_card ),
			self::background_region( $body_card, $styling, $overlap_body_card )
		);
	}

	/**
	 * Everything that sits on the accent band: the header image and either the
	 * message card or, when the message is empty, the body card.
	 *
	 * In Figma the band is a fixed 200px and the message card straddles its
	 * lower edge. Tables cannot overlap a box across two cells, so the card's
	 * wrapper cell is painted with a hard-stop gradient instead: accent above
	 * the stop, page background below it. Clients without gradient support
	 * (classic Outlook for Windows) keep the solid accent fallback, which runs
	 * the band to the bottom of the card.
	 *
	 * @since 3.14.0
	 *
	 * @param string $message_html      Message card contents, or empty.
	 * @param string $body_card         Pre-rendered body-card row.
	 * @param array  $styling           Styling values.
	 * @param array  $colors            Color values.
	 * @param bool   $overlap_body_card Whether the body card crosses the band.
	 *
	 * @return string
	 */
	private static function accent_region( $message_html, $body_card, $styling, $colors, $overlap_body_card ) {

		$accent      = esc_attr( $colors['accent'] );
		$background  = esc_attr( $colors['background'] );
		$card_config = self::accent_card_config( $message_html, $body_card, $colors, $accent, $background, $overlap_body_card );

		$open_inner  = '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0"'
			. ' style="width:100%;max-width:550px;">';
		$close_inner = '</table>';

		$header_row = sprintf(
			'<tr><td align="center" style="padding:42px 24px %1$s 24px;">%2$s%3$s%4$s</td></tr>',
			'0',
			$open_inner,
			self::header_image( $styling ),
			$close_inner
		);

		$card_row = sprintf(
			'<tr><td%1$s align="center" style="padding:0 24px %2$s 24px;background-color:%3$s;background:%4$s">'
			. '%5$s%6$s%7$s'
			. '</td></tr>',
			$card_config['class'],
			$card_config['bottom_padding'],
			$accent,
			$card_config['gradient'],
			$open_inner,
			$card_config['card'],
			$close_inner
		);

		return sprintf(
			'<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" border="0"'
			. ' style="background-color:%1$s;">'
			. '%2$s%3$s'
			. '</table>',
			$accent,
			$header_row,
			$card_row
		);
	}

	/**
	 * The card configuration for the selected accent-region route.
	 *
	 * @since 3.14.0
	 *
	 * @param string $message_html      Message card contents, or empty.
	 * @param string $body_card         Pre-rendered body-card row.
	 * @param array  $colors            Color values.
	 * @param string $accent            Escaped accent color.
	 * @param string $background        Escaped page background color.
	 * @param bool   $overlap_body_card Whether the body card crosses the band.
	 *
	 * @return array
	 */
	private static function accent_card_config( $message_html, $body_card, $colors, $accent, $background, $overlap_body_card ) {

		if ( $overlap_body_card ) {
			return [
				'card'           => $body_card,
				'class'          => ' class="sc-email-body-overlap"',
				'bottom_padding' => '0',
				'gradient'       => sprintf(
					'linear-gradient(to bottom,%1$s 0%%,%1$s %3$dpx,%2$s %3$dpx,%2$s 100%%);',
					$accent,
					$background,
					self::BODY_CARD_OVERLAP_DEPTH
				),
			];
		}

		return [
			'card'           => self::message_card( $message_html, $colors ),
			'class'          => '',
			'bottom_padding' => '24px',
			'gradient'       => sprintf(
				'linear-gradient(to bottom,%1$s 0%%,%1$s %3$d%%,%2$s %3$d%%,%2$s 100%%);',
				$accent,
				$background,
				self::MESSAGE_CARD_BAND_STOP
			),
		];
	}

	/**
	 * The header image row, or nothing.
	 *
	 * With no image configured the accent band still renders at its padded
	 * height; it simply has nothing inside it. That is the approved empty state.
	 *
	 * @since 3.14.0
	 *
	 * @param array $styling Styling values.
	 *
	 * @return string
	 */
	private static function header_image( $styling ) {

		if ( empty( $styling['header_image'] ) ) {
			return '';
		}

		return sprintf(
			'<tr><td align="center" style="padding:0 0 24px 0;">'
			. '<img src="%1$s" width="%2$d" alt="%3$s"'
			. ' style="display:block;border:0;outline:none;text-decoration:none;width:%2$dpx;max-width:100%%;height:auto;" />'
			. '</td></tr>',
			esc_url( $styling['header_image'] ),
			Styling::header_image_width( $styling ),
			esc_attr( get_bloginfo( 'name' ) )
		);
	}

	/**
	 * The populated-message card.
	 *
	 * The caller decides whether the Email Message is empty and does not invoke
	 * this method for that route, so this method only renders populated copy.
	 *
	 * @since 3.14.0
	 *
	 * @param string $message_html Message contents, already escaped.
	 * @param array  $colors       Color values.
	 *
	 * @return string
	 */
	private static function message_card( $message_html, $colors ) {

		return sprintf(
			'<tr><td class="sc-email-message" style="padding:0;">'
			. '<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" border="0"'
			. ' style="background-color:%1$s;border:1px solid rgba(141, 141, 141, 0.15);border-radius:16px;">'
			. '<tr><td style="padding:24px;font-family:%2$s;font-size:16px;line-height:1.4;color:%3$s;">'
			. '%4$s'
			. '</td></tr>'
			. '</table>'
			. '</td></tr>',
			esc_attr( $colors['body'] ),
			self::FONT_STACK,
			esc_attr( $colors['text'] ),
			$message_html
		);
	}

	/**
	 * The pre-rendered body-card row.
	 *
	 * @since 3.14.0
	 *
	 * @param string $body_html Body-card rows.
	 * @param array  $colors    Color values.
	 *
	 * @return string
	 */
	private static function body_card( $body_html, $colors ) {

		return sprintf(
			'<tr><td style="padding:0;">'
			. '<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" border="0"'
			. ' style="background-color:%1$s;border:1px solid rgba(141, 141, 141, 0.15);border-radius:16px;">'
			. '%2$s'
			. '</table>'
			. '</td></tr>',
			esc_attr( $colors['body'] ),
			$body_html
		);
	}

	/**
	 * The background-region body card, when it is not overlapping, and the
	 * powered-by row.
	 *
	 * @since 3.14.0
	 *
	 * @param string $body_card         Pre-rendered body-card row.
	 * @param array  $styling           Styling values.
	 * @param bool   $overlap_body_card Whether the body card is in the accent region.
	 *
	 * @return string
	 */
	private static function background_region( $body_card, $styling, $overlap_body_card ) {

		return sprintf(
			'<table role="presentation" width="100%%" cellpadding="0" cellspacing="0" border="0"'
			. ' style="width:100%%;max-width:550px;">'
			. '%1$s'
			. '%2$s'
			. '</table>',
			$overlap_body_card ? '' : $body_card,
			self::powered_by( $styling )
		);
	}

	/**
	 * The powered-by row, unless branding is hidden.
	 *
	 * SVG does not render in email, so this is a PNG served at 2x and
	 * constrained to its display size.
	 *
	 * @since 3.14.0
	 *
	 * @param array $styling Styling values.
	 *
	 * @return string
	 */
	private static function powered_by( $styling ) {

		if ( ! empty( $styling['hide_branding'] ) ) {
			return '';
		}

		return sprintf(
			'<tr><td align="center" style="padding:24px 0 0 0;">'
			. '<table role="presentation" cellpadding="0" cellspacing="0" border="0"><tr>'
			. '<td style="padding:0 5px 0 0;font-family:%1$s;font-size:12px;line-height:1.4;color:#1d2327;opacity:0.5;">%2$s</td>'
			. '<td style="padding:0;">'
			. '<img src="%3$s" width="126" height="17" alt="%4$s"'
			. ' style="display:block;border:0;outline:none;text-decoration:none;opacity:0.5;" />'
			. '</td>'
			. '</tr></table>'
			. '</td></tr>',
			self::FONT_STACK,
			esc_html__( 'Powered by', 'sugar-calendar-lite' ),
			esc_url( plugins_url( 'assets/images/emails/logo-powered-by.png', SC_PLUGIN_FILE ) ),
			esc_attr__( 'Sugar Calendar Events', 'sugar-calendar-lite' )
		);
	}
}
