	/**
	 * Per-request memo of is_active(); relay_ready() reads options and is called
	 * from two hooks.
	 *
	 * @since 3.15.0
	 *
	 * @var bool|null
	 */
	private static $active = null;

	/**
	 * Register hooks.
	 *
	 * @since 3.15.0
	 *
	 * @return void
	 */
	public function hooks() {

		add_action( 'admin_enqueue_scripts', [ $this, 'enqueue_assets' ] );
		add_action( 'admin_footer', [ $this, 'render_mount' ] );
		add_action( 'sugar_calendar_admin_pages_events_subheader_actions', [ $this, 'render_create_event_button' ] );
	}

	/**
	 * Whether the shell mounts on this request.
	 *
	 * Toggle on, Abilities API present, relay callable, user passes a funnel
	 * capability, and the screen is one of ours (the same check the legacy flyout uses).
	 * Without the Abilities API (WordPress before 6.9) every prompt fails with
	 * `sc_ai_no_abilities`, so the shell stays out and the legacy flyout renders.
	 *
	 * @since 3.15.0
	 *
	 * @return bool
	 */
	public static function is_active(): bool {

		if ( self::$active !== null ) {
			return self::$active;
		}

		// is_sc_admin_page() rather than is_admin_page(): it is the same
		// condition that enqueues admin-tailwind.css, which carries every style
		// this UI needs. The manifest check keeps a source-only checkout from
		// printing an empty mount node and hiding the flyout with it.
		self::$active = is_admin()
			&& ! wp_doing_ajax()
			&& Availability::is_enabled()
			&& Abilities::is_available()
			&& Availability::relay_ready()
			&& Availability::user_can_use()
			&& sugar_calendar()->get_admin()->is_sc_admin_page()
			&& file_exists( SC_PLUGIN_DIR . self::ASSET_MANIFEST );

		return self::$active;
	}

	/**
	 * Print the node the React app mounts into.
	 *
	 * @since 3.15.0
	 *
	 * @return void
	 */
	public function render_mount() {

		if ( ! self::is_active() ) {
			return;
		}

		printf( '<div id="%s" class="sugar-calendar-scope"></div>', esc_attr( self::MOUNT_ID ) );
	}

	/**
	 * Print the "New Event with Gia AI" button next to Add New Event.
	 *
	 * The app binds it by its data attribute and opens the panel on the create funnel.
	 *
	 * @since 3.15.0
	 *
	 * @return void
	 */
	public function render_create_event_button() {

		if (
			! self::is_active()
			|| ! in_array( Funnels::CREATE_EVENT, Availability::funnels(), true )
			|| ! current_user_can( Availability::funnel_capability( Funnels::CREATE_EVENT ) )
		) {
			return;
		}

		UI::button(
			[
				'text'   => esc_html__( 'New Event with Gia AI', 'sugar-calendar-lite' ),
				'type'   => 'tertiary',
				'size'   => 'sm',
				'class'  => 'sugar-calendar-btn-gia-ai',
				'submit' => false,
				'data'   => [ 'sc-gia-ai-funnel' => Funnels::CREATE_EVENT ],
			]
		);
	}

	/**
	 * Enqueue the bundle and its bootstrap data.
	 *
	 * The manifest is generated by the JSX build and is absent on a source-only
	 * checkout until assets are built.
	 *
	 * @since 3.15.0
	 *
	 * @return void
	 */
	public function enqueue_assets() {

		if ( ! self::is_active() ) {
			return;
		}

		$manifest_path = SC_PLUGIN_DIR . self::ASSET_MANIFEST;

		if ( ! file_exists( $manifest_path ) ) {
			return;
		}

		$manifest = include $manifest_path;

		if ( ! is_array( $manifest ) || ! isset( $manifest['dependencies'], $manifest['version'] ) ) {
			return;
		}

		ReactJsxRuntime::ensure_registered();

		wp_enqueue_script(
			self::HANDLE,
			SC_PLUGIN_ASSETS_URL . 'jsx/build/admin/gia-ai.js',
			$manifest['dependencies'],
			$manifest['version'],
			true
		);

		wp_localize_script( self::HANDLE, 'sugar_calendar_gia_ai', $this->get_bootstrap_data() );
	}

