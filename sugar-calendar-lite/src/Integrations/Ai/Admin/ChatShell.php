	/**
	 * UTM-tagged sugarcalendar.com URL.
	 *
	 * @since 3.15.0
	 *
	 * @param string $url     Base URL.
	 * @param string $content UTM content.
	 *
	 * @return string
	 */
	private function get_utm_url( string $url, string $content ): string {

		return Helpers::get_utm_url( $url, $this->get_utm_args( $content ) );
	}

	/**
	 * The panel's UTM parameters.
	 *
	 * @since 3.15.0
	 *
	 * @param string $content UTM content.
	 *
	 * @return array
	 */
