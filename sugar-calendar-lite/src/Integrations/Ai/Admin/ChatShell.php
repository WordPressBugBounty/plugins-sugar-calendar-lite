	/**
	 * Funnels the current user may start, with their copy.
	 *
	 * @since 3.15.0
	 *
	 * @return array
	 */
	private function get_funnels(): array {

		$registry = Funnels::all();
		$funnels  = [];

		foreach ( Availability::funnels() as $slug ) {
			$funnel = $registry[ $slug ] ?? null;

			if ( $funnel === null || ! current_user_can( Availability::funnel_capability( $slug ) ) ) {
				continue;
			}

			$funnels[] = $funnel->ui();
		}

		return $funnels;
	}

	/**
	 * Record types the "+" menu offers the current user.
	 *
	 * @since 3.15.0
	 *
	 * @return array
	 */
	private function get_insert_types(): array {

		$types = [];

		foreach ( ( new Mentions() )->available_types() as $type => $row ) {
			$types[] = [
				'type'         => $type,
				'label'        => $row['label'],
				'icon'         => $row['icon'],
				'list'         => $row['list'],
				'list_input'   => (object) $row['list_input'],
				'search'       => $row['search'],
				'search_input' => (object) $row['search_input'],
				'collection'   => $row['collection'],
				'name'         => $row['name'],
			];
		}

		return $types;
	}

